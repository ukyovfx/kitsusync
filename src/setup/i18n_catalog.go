func tr(lang, key string) string {
	if lang != "en" {
		lang = "ja"
	}
	if value, ok := uiText[lang][key]; ok {
		return value
	}
	return "[missing translation: " + key + "]"
}

func trf(lang, key string, args ...any) string {
	return fmt.Sprintf(tr(lang, key), args...)
}
